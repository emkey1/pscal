#!/usr/bin/env python3
"""KPI levels on the B0 baseline (plan 6.5), from the committed unit reports.

    python3 Tests/aether_doc_bench/results/replays_20261012/kpi_baseline.py > KPI_baseline.md

G1 / Gf: medium guide, tasks_v2_pos + tasks_cs, first-attempt / final exact.
S: first attempts that exit 0 with the wrong output, all four B0 suites.
TRAP-SW: silent-wrong first attempts per trap (B1), medium and card.
P1: card first attempt on tasks_v2_pos + tasks_cs (P0), and its gap to G1.
First-attempt classes come from the harness's own classify_attempt.
"""
import collections, glob, gzip, importlib.util, json, pathlib, sys
ROOT = pathlib.Path(__file__).resolve().parents[4]
RES = ROOT / "Tests" / "aether_doc_bench" / "results"
spec = importlib.util.spec_from_file_location("aether_doc_bench", ROOT / "tools" / "aether_doc_bench.py")
bench = importlib.util.module_from_spec(spec); sys.modules["aether_doc_bench"] = bench; spec.loader.exec_module(bench)
SETS = [("local", "b0_20261007"), ("local 4-bit", "b0_devstral_mlx4bit_20261011"), ("hosted", "b0_openrouter_20261010")]

def units(d, board):
    found = glob.glob(str(RES / d / board / "*__r[0-9].json*")) + glob.glob(str(RES / d / board / "infra_pending" / "*__r[0-9].json*"))
    for p in sorted(x for x in found if x.endswith((".json", ".json.gz"))):
        r = json.loads(gzip.decompress(open(p, "rb").read()) if p.endswith(".gz") else open(p).read())
        name = pathlib.Path(p).name.split("__")
        for v in r["destinations"][0]["variants"]:
            for c in v["results"]:
                first = bench.classify_attempt(bench.first_attempt_of(c))
                yield {"model": name[0], "suite": name[1], "doc": v.get("doc_name"), "task": c["task_id"],
                       "key": (pathlib.Path(p).name.replace(".gz", ""), v.get("doc_name"), c["task_id"], c.get("repeat_index")),
                       "first": first, "fx": bool(c["run"]["exact_stdout_match"])}

def replay_pass(name):
    """First attempts whose pass state changes under a replayed binary: key -> new pass state."""
    path = pathlib.Path(__file__).with_name(name)
    if not path.is_file():
        return None
    r = json.loads(path.read_text())
    return {(pathlib.Path(f["report"]).name.replace(".gz", ""), f["doc"], f["task_id"], f["repeat_index"]): f["new_class"] == "pass"
            for f in r["flips"] if f["kind"] == "first"}, r

REPLAYS = [(label, replay_pass(name)) for label, name in (("L0 2026-10-07-1", "B_L0.json"), ("L1 2026-10-08-1", "B_L1.json"))]
REPLAYS = [(label, x) for label, x in REPLAYS if x]

def pct(a, b): return "-" if not b else f"{100 * a / b:.1f}% ({a}/{b})"
out = ["# KPI levels on the B0 baseline (aether 2026-10-06-1)", "",
       "Generated by `kpi_baseline.py` from the committed unit reports. Provisional targets are the plan's (6.5).", ""]
out += ["## G1 / Gf (medium, tasks_v2_pos + tasks_cs) and S (silent-wrong first attempts, all B0 suites)", "",
        "| set | model | G1 first attempt | Gf after repair | S level | cases |" + "".join(f" G1 on {l} (replay) |" for l, _ in REPLAYS),
        "|---|---|---|---|---|---|" + "---|" * len(REPLAYS)]
g1 = {}
for label, d in SETS:
    cases = [c for c in units(d, "B0") if c["doc"] == "medium"]
    for m in sorted({c["model"] for c in cases}):
        cm = [c for c in cases if c["model"] == m]; g = [c for c in cm if c["suite"] in ("tasks_v2_pos", "tasks_cs")]
        if not g: continue
        g1[(label, m)] = sum(c["first"] == "pass" for c in g) / len(g)
        out.append(f"| {label} | {m} | {pct(sum(c['first'] == 'pass' for c in g), len(g))} | {pct(sum(c['fx'] for c in g), len(g))} | "
                   f"{pct(sum(c['first'] == 'silent_wrong' for c in cm), len(cm))} | {len(cm)} |"
                   + "".join(f" {pct(sum(fl.get(c['key'], c['first'] == 'pass') for c in g), len(g))} |" for _, (fl, _r) in REPLAYS))
out += ["", "Provisional targets: G1 >= 90%, Gf >= 97%, S level <= 2%.", ""]
if REPLAYS:
    out += ["## Paired replay of every stored attempt (S and R gates)", "",
            "| binary | first attempts | pass before -> after | fail->pass | pass->fail | into silent-wrong | repair attempts pass before -> after | unwaived pass->fail (all attempts) |",
            "|---|---|---|---|---|---|---|---|"]
    for label, (_fl, r) in REPLAYS:
        t = r["tallies"]["first"]; rp = r["tallies"].get("repair") or {}
        out.append(f"| {label} | {t['attempts']} | {t['old_pass']} -> {t['new_pass']} | {t['fail_to_pass']} | {t['pass_to_fail']} | {t['into_silent_wrong']} | "
                   f"{rp.get('old_pass', '-')} -> {rp.get('new_pass', '-')} | {len(r['unwaived'])} |")
    out += ["", "First-attempt class moves: " + "; ".join(f"{label}: " + ", ".join(f"{k} {v}" for k, v in sorted(r["tallies"]["first"]["transitions"].items(), key=lambda kv: -kv[1])) for label, (_f, r) in REPLAYS), ""]
out += [
        "## P1 (card first attempt, tasks_v2_pos + tasks_cs) and its gap to G1", "",
        "| set | model | P1 | G1 | gap (points) |", "|---|---|---|---|---|"]
for label, d in SETS:
    cases = [c for c in units(d, "P0") if c["suite"] in ("tasks_v2_pos", "tasks_cs")]
    for m in sorted({c["model"] for c in cases}):
        cm = [c for c in cases if c["model"] == m]; p1 = sum(c["first"] == "pass" for c in cm) / len(cm)
        g = g1.get((label, m)) if (label, m) in g1 else g1.get(("local", m))
        out.append(f"| {label} | {m} | {pct(sum(c['first'] == 'pass' for c in cm), len(cm))} | {'-' if g is None else f'{100 * g:.1f}%'} | "
                   f"{'-' if g is None else f'{100 * (g - p1):.1f}'} |")
out += ["", "Provisional target: gap <= 10 points.", "", "## TRAP-SW (B1): silent-wrong first attempts per trap", ""]
traps = collections.defaultdict(lambda: collections.Counter()); tot = collections.Counter(); fa = collections.Counter(); n = collections.Counter()
for label, d in SETS:
    for c in units(d, "B1"):
        n[c["doc"]] += 1; fa[c["doc"]] += c["first"] == "pass"; tot[(c["task"], c["doc"])] += 1
        if c["first"] == "silent_wrong": traps[c["task"]][c["doc"]] += 1
out += [f"Units pooled over every committed B1 report: medium {n['medium']} first attempts, first-attempt pass {pct(fa['medium'], n['medium'])}; "
        f"card {n['card']}, {pct(fa['card'], n['card'])}. Provisional target: suite first attempt >= 80%; each fixed trap 0 on replay.", "",
        "| trap | medium SW / attempts | card SW / attempts |", "|---|---|---|"]
for t in sorted({k[0] for k in tot}, key=lambda t: -(traps[t]["medium"] + traps[t]["card"])):
    out.append(f"| {t} | {traps[t]['medium']} / {tot[(t, 'medium')]} | {traps[t]['card']} / {tot[(t, 'card')]} |")
print("\n".join(out))
